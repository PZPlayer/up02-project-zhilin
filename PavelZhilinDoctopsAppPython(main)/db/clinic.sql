-- ---------- 1. Очистка (чтобы скрипт можно было запускать повторно) ----------
DROP VIEW  IF EXISTS v_order_totals;
DROP TABLE IF EXISTS order_items CASCADE;
DROP TABLE IF EXISTS orders      CASCADE;
DROP TABLE IF EXISTS doctors     CASCADE;
DROP TABLE IF EXISTS specialties CASCADE;
DROP TABLE IF EXISTS users       CASCADE;
DROP TABLE IF EXISTS roles       CASCADE;

-- ---------- 2. Таблицы ----------

-- Справочник ролей
CREATE TABLE roles (
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(30) NOT NULL UNIQUE
);

-- Пользователи
CREATE TABLE users (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login     VARCHAR(50)  NOT NULL UNIQUE,
    full_name VARCHAR(120) NOT NULL,
    role_id   INTEGER      NOT NULL REFERENCES roles(id)
);

-- Справочник специальностей (вынесен из таблицы врачей — 3НФ)
CREATE TABLE specialties (
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(60) NOT NULL UNIQUE
);

-- Врачи (в приложении — «товар» каталога)
CREATE TABLE doctors (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    specialty_id     INTEGER       NOT NULL REFERENCES specialties(id),
    full_name        VARCHAR(120)  NOT NULL,
    experience_years INTEGER       NOT NULL DEFAULT 0  CHECK (experience_years >= 0),
    price            NUMERIC(10,2) NOT NULL CHECK (price >= 0),
    slots            INTEGER       NOT NULL DEFAULT 0  CHECK (slots >= 0),  -- свободные талоны
    photo            VARCHAR(100)  NOT NULL DEFAULT ''                       -- пусто = заглушка picture.png
);

-- Заказы (записи на приём)
CREATE TABLE orders (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_date DATE    NOT NULL DEFAULT CURRENT_DATE,
    client_id  INTEGER NOT NULL REFERENCES users(id)
);

-- Состав заказа
CREATE TABLE order_items (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id  INTEGER       NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    doctor_id INTEGER       NOT NULL REFERENCES doctors(id),
    quantity  INTEGER       NOT NULL CHECK (quantity > 0),
    price     NUMERIC(10,2) NOT NULL CHECK (price >= 0)   -- цена на момент заказа
);

-- Индексы по внешним ключам
CREATE INDEX idx_users_role         ON users(role_id);
CREATE INDEX idx_doctors_specialty  ON doctors(specialty_id);
CREATE INDEX idx_orders_client      ON orders(client_id);
CREATE INDEX idx_order_items_order  ON order_items(order_id);
CREATE INDEX idx_order_items_doctor ON order_items(doctor_id);

-- Представление: сумма по каждому заказу
CREATE VIEW v_order_totals AS
SELECT o.id AS order_id, o.order_date, u.full_name AS client,
       SUM(oi.quantity * oi.price) AS total
FROM orders o
JOIN users u        ON u.id = o.client_id
JOIN order_items oi ON oi.order_id = o.id
GROUP BY o.id, o.order_date, u.full_name;

